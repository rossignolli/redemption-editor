"""Writes fake_runtime.h, a reshade::api::effect_runtime
whose every method does nothing (false, 0, null), for the UI harness
(ReplayEditorUiTests.vcxproj). Run again after a ReShade header update:

    py -3 tools/ui_harness/gen_fake_runtime.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INCLUDE = ROOT / "external" / "reshade" / "include"
OUT = Path(__file__).resolve().parent / "fake_runtime.h"


def class_body(text: str, name: str) -> str:
    match = re.search(r"struct __declspec\(novtable\) " + name + r"\b[^{]*\{", text)
    if not match:
        raise SystemExit(f"class {name} not found")
    depth = 1
    at = match.end()
    while depth:
        if text[at] == "{":
            depth += 1
        elif text[at] == "}":
            depth -= 1
        at += 1
    return text[match.end():at - 1]


PURE = re.compile(r"^\s*virtual\s+(.*?)\s*=\s*0\s*;\s*$")


def overrides(body: str) -> list[str]:
    out = []
    for line in body.splitlines():
        m = PURE.match(line)
        if not m:
            continue
        decl = re.sub(r"\s+", " ", m.group(1)).strip()
        name = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*\(", decl)
        ret = decl[: name.start()].strip()
        body_text = "{}" if ret == "void" else "{ return {}; }"
        out.append(f"        {decl} override {body_text}")
    return out


def main() -> None:
    device_h = (INCLUDE / "reshade_api_device.hpp").read_text(encoding="utf-8")
    api_h = (INCLUDE / "reshade_api.hpp").read_text(encoding="utf-8")
    lines = []
    lines += overrides(class_body(device_h, "api_object"))
    lines += overrides(class_body(device_h, "device_object"))
    lines += overrides(class_body(api_h, "effect_runtime"))
    text = "\n".join([
        "#pragma once",
        "",
        "// Generated by tools/ui_harness/gen_fake_runtime.py, do not edit.",
        "// An effect runtime for the UI harness: no keys down, no device, no back buffer.",
        "",
        "#include <reshade.hpp>",
        "",
        "#pragma warning(push)",
        "#pragma warning(disable : 4100) // unreferenced formal parameter",
        "namespace ui_harness",
        "{",
        "    using namespace reshade::api;",
        "    struct FakeRuntime final : effect_runtime",
        "    {",
        *lines,
        "    };",
        "}",
        "#pragma warning(pop)",
        "",
    ])
    OUT.write_text(text, encoding="utf-8", newline="\r\n")
    print(f"{len(lines)} methods -> {OUT}")


if __name__ == "__main__":
    main()
